_GABARITS = None


def get_lang() -> str:
    lang = st.session_state.get("lang", DEFAUT)
    return lang if lang in LANGUES else DEFAUT


def t(cle: str, **variables) -> str:
    """Texte traduit dans la langue choisie (français si la traduction manque)."""
    texte = TEXTES.get(get_lang(), {}).get(cle) or TEXTES[DEFAUT].get(cle, cle)
    return texte.format(**variables) if variables else texte


def _gabarits() -> list:
    """Modèles des messages du code (clés « msg_ ») transformés en expressions régulières."""
    global _GABARITS
    if _GABARITS is None:
        _GABARITS = []
        for cle, modele in TEXTES[DEFAUT].items():
            if cle.startswith("msg_"):
                motif = re.sub(r"\\\{(\w+)\\\}", r"(?P<\1>.+?)", re.escape(modele))
                _GABARITS.append((cle, re.compile(motif, re.S)))
    return _GABARITS


def tm(message):
    """Traduit un message renvoyé par authentifications.py ou rooms.py (écrits en français).
    Si le message est inconnu, il est renvoyé tel quel."""
    if get_lang() == DEFAUT or not isinstance(message, str):
        return message
    for cle, motif in _gabarits():
        trouve = motif.fullmatch(message)
        if trouve:
            modele = TEXTES.get(get_lang(), {}).get(cle)
            return modele.format(**trouve.groupdict()) if modele else message
    return message


def ia_language() -> str:
    """Langue dans laquelle l'IA doit écrire les questions."""
    return LANGUES_IA.get(get_lang(), LANGUES_IA[DEFAUT])


def apply_direction() -> None:
    """Arabe : affichage de droite à gauche (le panneau de connexion et le code de room restent normaux)."""
    if get_lang() == "ar":
        st.markdown(
            "<style>.stApp { direction: rtl; } "
            ".room-code, .st-key-auth_card, .st-key-lang_bar { direction: ltr; }</style>",
            unsafe_allow_html=True,
        )


def _changer_langue(cle_widget: str) -> None:
    st.session_state["lang"] = st.session_state[cle_widget]


def language_selector(where: str = "sidebar", key: str = "lang_widget", compact: bool = False) -> None:
    """Sélecteur de langue. where = "sidebar" (barre latérale) ou "main" (dans la page).
    compact = petit sélecteur sans titre (page de connexion)."""
    zone = st.sidebar if where == "sidebar" else st
    codes = list(LANGUES)
    zone.selectbox(
        "🌐 " + t("language"),
        codes,
        index=codes.index(get_lang()),
        format_func=(lambda c: "🌐 " + LANGUES[c]) if compact else (lambda c: LANGUES[c]),
        key=key,
        on_change=_changer_langue,
        args=(key,),
        label_visibility="collapsed" if compact else "visible",
    )
    apply_direction()